         'branch_admin',
         'branch_team_member'
       )
  )
$$;

-- New: replaces "is_branch_user(b) AND current_role() IN ('master','admin')"
-- in policies that gated by master/admin specifically.
create or replace function public.is_branch_master_or_admin(target_branch uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
     where user_id = auth.uid()
       and is_active = true
       and branch_id = target_branch
       and role in ('branch_master_admin', 'branch_admin')
  )
$$;

-- New: replaces "is_branch_user(b) AND current_role() = 'branch_chairman'".
create or replace function public.is_branch_chairman(target_branch uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
     where user_id = auth.uid()
       and is_active = true
       and branch_id = target_branch
       and role = 'branch_chairman'
  )
$$;

-- -------------------------------------------------------------------------
-- 3) Rewrite policies that called current_role() directly
-- -------------------------------------------------------------------------

drop policy if exists branches_update on public.branches;
create policy branches_update on public.branches
  for update using (
    public.is_taylab_staff()
    or public.is_branch_master_or_admin(id)
  )
  with check (
    public.is_taylab_staff()
    or public.is_branch_master_or_admin(id)
  );

drop policy if exists profiles_insert_branch_master_admin on public.profiles;
create policy profiles_insert_branch_master_admin on public.profiles
  for insert with check (
    branch_id is not null
    and public.is_branch_master_or_admin(branch_id)
  );

drop policy if exists profiles_update_branch_master_admin on public.profiles;
create policy profiles_update_branch_master_admin on public.profiles
  for update using (
    branch_id is not null
    and public.is_branch_master_or_admin(branch_id)
  );

drop policy if exists applications_update_branch_admin on public.applications;
create policy applications_update_branch_admin on public.applications
  for update using (
    public.is_taylab_staff()
    or public.is_branch_admin_team(branch_id)
    or public.is_branch_chairman(branch_id)
  );

-- -------------------------------------------------------------------------
-- 4) Rewrite profiles_select_self + profiles_update_self
-- -------------------------------------------------------------------------
-- Under multi-profile, "self" means "all rows where user_id = my auth id"
-- — a user can see/update any of their own profile rows.

drop policy if exists profiles_select_self on public.profiles;
create policy profiles_select_self on public.profiles
  for select using (user_id = auth.uid());

drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles
  for update using (user_id = auth.uid())
  with check (
    user_id = auth.uid()
    -- Self-update cannot change role. Reads the original row's role to
    -- compare against the new value.
    and role = (select role from public.profiles p2 where p2.id = profiles.id)
  );

